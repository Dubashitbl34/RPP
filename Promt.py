# функция составляет промпт из параметров для модели
def user_prompt(gender, weight, height, goal, exclusions):
    if exclusions:
        exclusions_str = ", ".join(exclusions)
    else:
        exclusions_str = "нет ограничений"
    
    return f"""
    Составь меню. Параметры пользователя:
    - Пол: {gender}
    - Вес: {weight} кг
    - Рост: {height} см
    - Цель: похудеть на {goal} кг
    - ИСКЛЮЧИТЬ ИЗ МЕНЮ абсолютно все блюда, содержащие: {exclusions_str}
    """